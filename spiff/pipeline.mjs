#!/usr/bin/env node
/**
 * BPMN IR → XML pipeline.
 *
 * Reads an IR JSON document from stdin, runs three deterministic passes:
 *   1. normalizeGateways   — eliminate task/event fan-out and fan-in
 *   2. assertGatewayPairing — reject mismatched opens/closes pairs before compiling
 *   3. compileIRtoBpmn     — build a bpmn-moddle tree, add DI layout
 *
 * For processes WITHOUT lanes: the same builder runs on one hidden lane, and the
 * frontend (spiff/src/utils/bpmnLayout.js) regenerates the layout on import.
 * For processes WITH lanes (pools): the manual builder lays out every lane; the
 * participant's process and drops the pool and lane bands entirely (still true
 * at 1.3.0, verified WI-002042), so BPMNDI is generated by buildManualLaneDI(),
 * which the frontend then keeps verbatim.
 *
 * buildManualLaneDI places one node per (lane, column) cell and routes every
 * edge through reserved gutters and strips on allocated channels, so no edge
 * enters a shape it does not connect to and no two shapes overlap. See the
 * comments on the routing model there, and one_bpmn/tests/test_lane_layout.py
 * for the guarantees that are pinned.
 *
 * Writes { ok, xml, problems:[{kind, message}] } to stdout.
 * Semantic validation is handled by the Python bpmn_validator layer.
 *
 * Invoked from bpmn_ir_pipeline.compile_ir() via subprocess.
 */

