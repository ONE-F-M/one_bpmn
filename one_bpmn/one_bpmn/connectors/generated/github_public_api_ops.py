def list_all_open_issues(params, ctx):
    import requests
    import re
    
    owner = params.get('owner')
    repo = params.get('repo')
    
    if not owner or not repo:
        return {'error': 'Both owner and repo parameters are required'}
    
    # Maximum pages to fetch (30 items per page = 300 issues max)
    max_pages = 10
    
    # GitHub API endpoint
    base_url = 'https://api.github.com'
    url = f'{base_url}/repos/{owner}/{repo}/issues'
    
    all_issues = []
    page_count = 0
    
    # Headers for GitHub API
    headers = {
        'Accept': 'application/vnd.github.v3+json',
        'User-Agent': 'Processa-Connector'
    }
    
    # Query parameters
    query_params = {
        'state': 'open',
        'per_page': 30
    }
    
    while url and page_count < max_pages:
        try:
            response = requests.get(url, headers=headers, params=query_params if page_count == 0 else None, timeout=30)
            response.raise_for_status()
            
            page_issues = response.json()
            
            # Filter out pull requests and extract required fields
            for issue in page_issues:
                # GitHub's issues endpoint includes pull requests
                # Pull requests have a 'pull_request' key
                if 'pull_request' not in issue:
                    all_issues.append({
                        'number': issue.get('number'),
                        'title': issue.get('title'),
                        'state': issue.get('state'),
                        'author': issue.get('user', {}).get('login') if issue.get('user') else None
                    })
            
            page_count += 1
            
            # Parse Link header for next page
            link_header = response.headers.get('Link', '')
            next_url = None
            
            if link_header:
                # Parse Link header: <https://api.github.com/repos/.../issues?page=2>; rel="next"
                links = link_header.split(',')
                for link in links:
                    match = re.match(r'<([^>]+)>;\s*rel="next"', link.strip())
                    if match:
                        next_url = match.group(1)
                        break
            
            url = next_url
            
        except requests.exceptions.RequestException as e:
            return {
                'error': f'Failed to fetch issues: {str(e)}',
                'issues': all_issues,
                'pages_fetched': page_count
            }
    
    return {
        'issues': all_issues,
        'total_count': len(all_issues),
        'pages_fetched': page_count,
        'truncated': url is not None  # True if we hit the max_pages limit
    }
