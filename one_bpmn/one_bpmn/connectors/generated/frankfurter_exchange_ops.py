def get_latest_rates(params, ctx):
    """
    Fetch the latest exchange rates from Frankfurter API.
    Adds Bearer token authentication required by the gateway.
    """
    import requests
    
    # Build the URL
    base_url = ctx.get('base_url', 'https://api.frankfurter.dev/v1')
    url = f"{base_url}/latest"
    
    # Build query parameters
    query_params = {}
    if params.get('amount'):
        query_params['amount'] = params['amount']
    if params.get('from'):
        query_params['from'] = params['from']
    if params.get('to'):
        query_params['to'] = params['to']
    
    # Get the Bearer token from credential
    token = ctx.get('secret', {}).get('token', '')
    
    # Build headers with Bearer token
    headers = {
        'Authorization': f'Bearer {token}'
    }
    
    # Make the request
    response = requests.get(url, params=query_params, headers=headers)
    response.raise_for_status()
    
    # Return the parsed JSON response
    return response.json()
