def list_all_open_issues(params, ctx):
    """
    Fetch all open issues from ONE-F-M/one_bpmn repository,
    walking through pagination using the Link header.
    """
    import requests
    import re
    
    base_url = "https://api.github.com"
    url = f"{base_url}/repos/ONE-F-M/one_bpmn/issues"
    
    headers = {
        "Accept": "application/vnd.github.v3+json",
        "User-Agent": "Processa-Connector"
    }
    
    all_issues = []
    page = 1
    per_page = 100  # Max allowed by GitHub
    max_issues = 1000  # Cap to prevent unbounded execution
    
    while len(all_issues) < max_issues:
        response = requests.get(
            url,
            headers=headers,
            params={
                "state": "open",
                "per_page": per_page,
                "page": page
            },
            timeout=30
        )
        
        response.raise_for_status()
        issues = response.json()
        
        # No more issues
        if not issues:
            break
        
        all_issues.extend(issues)
        
        # Check Link header for next page
        link_header = response.headers.get("Link", "")
        if not link_header or 'rel="next"' not in link_header:
            break
        
        page += 1
    
    return {
        "issues": all_issues,
        "total_count": len(all_issues),
        "capped": len(all_issues) >= max_issues
    }
