def list_open_issues(params, ctx):
    """
    Retrieve all open issues from a GitHub repository with pagination.
    Follows the Link header (rel="next") up to 1000 issues or 20 pages.
    Filters out pull requests (items with "pull_request" field).
    """
    import requests
    import re
    
    owner = params.get("owner")
    repo = params.get("repo")
    
    if not owner or not repo:
        return {"error": "Both 'owner' and 'repo' parameters are required"}
    
    # Starting URL
    url = f"https://api.github.com/repos/{owner}/{repo}/issues"
    params_dict = {
        "state": "open",
        "per_page": 100
    }
    
    headers = {
        "Accept": "application/vnd.github.v3+json",
        "User-Agent": "Processa-Connector"
    }
    
    all_issues = []
    page_count = 0
    max_pages = 20
    max_issues = 1000
    
    while url and page_count < max_pages and len(all_issues) < max_issues:
        try:
            response = requests.get(url, params=params_dict if page_count == 0 else None, 
                                   headers=headers, timeout=30)
            response.raise_for_status()
            
            issues_page = response.json()
            
            # Filter out pull requests (they have a "pull_request" field)
            # and extract only the fields we want
            for item in issues_page:
                if "pull_request" not in item:
                    issue = {
                        "number": item.get("number"),
                        "title": item.get("title"),
                        "state": item.get("state"),
                        "author": item.get("user", {}).get("login") if item.get("user") else None
                    }
                    all_issues.append(issue)
                    
                    # Check if we've hit the max issues limit
                    if len(all_issues) >= max_issues:
                        break
            
            # Parse Link header for next page
            link_header = response.headers.get("Link", "")
            next_url = None
            
            if link_header:
                # Parse Link header: <https://api.github.com/...>; rel="next"
                links = link_header.split(",")
                for link in links:
                    match = re.match(r'<([^>]+)>;\s*rel="next"', link.strip())
                    if match:
                        next_url = match.group(1)
                        break
            
            url = next_url
            page_count += 1
            
        except requests.exceptions.RequestException as e:
            return {
                "error": f"Failed to fetch issues: {str(e)}",
                "issues": all_issues,
                "pages_fetched": page_count
            }
    
    return {
        "issues": all_issues,
        "total_count": len(all_issues),
        "pages_fetched": page_count,
        "truncated": len(all_issues) >= max_issues or page_count >= max_pages
    }
