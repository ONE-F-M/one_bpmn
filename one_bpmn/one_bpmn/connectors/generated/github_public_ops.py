def list_open_issues(params, ctx):
    """
    Fetch all open issues for a GitHub repository, following Link header pagination.
    Caps at 10 pages (~1000 issues) to prevent runaway calls on large repos.
    """
    import requests
    import re
    
    owner = params.get('owner')
    repo = params.get('repo')
    
    if not owner or not repo:
        return {
            'success': False,
            'error': 'Both owner and repo parameters are required'
        }
    
    base_url = 'https://api.github.com'
    url = f'{base_url}/repos/{owner}/{repo}/issues'
    
    all_issues = []
    page_count = 0
    max_pages = 10
    
    headers = {
        'Accept': 'application/vnd.github.v3+json',
        'User-Agent': 'Processa-Connector'
    }
    
    params_query = {
        'state': 'open',
        'per_page': 100
    }
    
    while url and page_count < max_pages:
        try:
            response = requests.get(url, headers=headers, params=params_query if page_count == 0 else None, timeout=30)
            response.raise_for_status()
            
            issues = response.json()
            
            # Extract the fields we want from each issue
            for issue in issues:
                all_issues.append({
                    'number': issue.get('number'),
                    'title': issue.get('title'),
                    'state': issue.get('state'),
                    'author': issue.get('user', {}).get('login') if issue.get('user') else None
                })
            
            page_count += 1
            
            # Parse Link header for next page
            link_header = response.headers.get('Link', '')
            url = None
            
            if link_header:
                # Link header format: <url>; rel="next", <url>; rel="last"
                links = link_header.split(',')
                for link in links:
                    match = re.match(r'<([^>]+)>;\s*rel="next"', link.strip())
                    if match:
                        url = match.group(1)
                        break
            
            # If no more issues returned, stop even if there's a next link
            if not issues:
                break
                
        except requests.exceptions.RequestException as e:
            return {
                'success': False,
                'error': f'GitHub API request failed: {str(e)}',
                'issues_fetched': len(all_issues),
                'pages_fetched': page_count
            }
    
    return {
        'success': True,
        'issues': all_issues,
        'total_count': len(all_issues),
        'pages_fetched': page_count,
        'capped': page_count >= max_pages and url is not None
    }
