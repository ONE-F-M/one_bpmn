def find_country_by_name(params, ctx):
    import requests
    
    country_name = params.get('country_name', '')
    if not country_name:
        return {
            'error': 'country_name is required',
            'capital': None,
            'region': None,
            'calling_code': None
        }
    
    url = f"https://restcountries.com/v3.1/name/{country_name}"
    
    try:
        response = requests.get(url, timeout=30)
        response.raise_for_status()
        
        countries = response.json()
        
        if not countries or not isinstance(countries, list) or len(countries) == 0:
            return {
                'capital': None,
                'region': None,
                'calling_code': None,
                'error': 'No country found'
            }
        
        # Take the first match
        country = countries[0]
        
        # Extract capital (first one if multiple)
        capital = None
        if country.get('capital') and isinstance(country.get('capital'), list):
            capital = country['capital'][0] if len(country['capital']) > 0 else None
        
        # Extract region
        region = country.get('region')
        
        # Construct calling code from idd.root + idd.suffixes
        calling_code = None
        idd = country.get('idd', {})
        if idd:
            root = idd.get('root', '')
            suffixes = idd.get('suffixes', [])
            if root:
                if suffixes and len(suffixes) > 0:
                    calling_code = root + suffixes[0]
                else:
                    calling_code = root
        
        return {
            'capital': capital,
            'region': region,
            'calling_code': calling_code
        }
    
    except requests.exceptions.HTTPError as e:
        return {
            'error': f'HTTP error: {str(e)}',
            'capital': None,
            'region': None,
            'calling_code': None
        }
    except Exception as e:
        return {
            'error': f'Failed to fetch country data: {str(e)}',
            'capital': None,
            'region': None,
            'calling_code': None
        }
