def list_all_open_issues(params, ctx):
    import requests
    import re
    
    all_issues = []
    max_issues = 1000  # Cap to prevent unbounded data
    url = f"{ctx['base_url']}/repos/ONE-F-M/one_bpmn/issues"
    
    try:
        while url and len(all_issues) < max_issues:
            response = requests.get(
                url,
                params={'state': 'open', 'per_page': 100},
                headers={
                    'Accept': 'application/vnd.github.v3+json',
                    'User-Agent': 'Processa-Connector'
                },
                timeout=30
            )
            
            if response.status_code != 200:
                return {
                    'error': f"GitHub API returned status {response.status_code}",
                    'message': response.text,
                    'issues': [],
                    'count': 0
                }
            
            page_issues = response.json()
            
            # Filter out pull requests (GitHub issues API includes PRs)
            page_issues = [issue for issue in page_issues if 'pull_request' not in issue]
            
            all_issues.extend(page_issues)
            
            # Parse Link header for next page
            link_header = response.headers.get('Link', '')
            url = None
            if link_header:
                for link in link_header.split(','):
                    if 'rel="next"' in link:
                        match = re.search(r'<([^>]+)>', link)
                        if match:
                            url = match.group(1)
                        break
        
        # Truncate if we hit the cap
        if len(all_issues) > max_issues:
            all_issues = all_issues[:max_issues]
            truncated = True
        else:
            truncated = False
        
        return {
            'issues': all_issues,
            'count': len(all_issues),
            'truncated': truncated
        }
    
    except requests.RequestException as e:
        return {
            'error': 'Request failed',
            'message': str(e),
            'issues': [],
            'count': 0
        }
