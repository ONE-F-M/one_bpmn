def execute():
	if not frappe.db.table_exists("BPMN Connector"):
		return

	from one_bpmn.one_bpmn.connectors.manifest import clear_manifest_cache
	from one_bpmn.one_bpmn.connectors.seed import import_manifest

	results = {}
	for manifest in GOOGLE_CONNECTORS:
		results[manifest["connectorId"]] = import_manifest(manifest, overwrite=False)

	clear_manifest_cache()
	frappe.db.commit()

	created = [c for c, state in results.items() if state != "skipped"]
	kept = [c for c, state in results.items() if state == "skipped"]
	if created:
		print(f"Seeded connectors: {', '.join(created)}")
	if kept:
		print(f"Already present, left as configured: {', '.join(kept)}")
