"""
Seed the four Google connectors into a fresh site.

Connectors are DocType rows, so a new site starts with an empty modeler until
something creates them. That used to be a directory of JSON manifests read at
runtime — which meant every connector existed twice, once as a file and once as
a row, and the two drifted apart the moment anyone edited a row. The files are
gone. This is the only definition, and it is applied once.

WHAT THIS IS
------------
A snapshot of a working installation, in the same portable shape that
``Export JSON`` produces on the connector form: four connectors, 25 operations,
their fields, and — for the 16 operations that are plain REST — the URL, query,
body and response mapping that let them run with no Python at all.

It is DATA, not behaviour, and it goes in through the ordinary import path
(``connectors.seed.import_manifest``) rather than a second bespoke writer. What
ships is therefore exactly what an export produces, which is what keeps the
snapshot honest.

IT DOES NOT OVERWRITE
---------------------
A connector that already exists is left exactly as it is. Sites set their own
base URLs, credentials, scopes and allowed roles, and a patch that re-applied on
every migrate would quietly undo that. Only what is missing is created.

Credentials are never seeded — a key belongs to the site, not the codebase.
"""

